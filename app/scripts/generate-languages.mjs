import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = new URL('../', import.meta.url);
const catalog = JSON.parse(readFileSync(new URL('src/lib/languages.json', root), 'utf8'));
const codes = catalog.languages.map((l) => l.code);
if (new Set(codes).size !== codes.length) throw new Error('Duplicate language code');
const variant = (code) =>
	code
		.split('-')
		.map((s) => s[0].toUpperCase() + s.slice(1).toLowerCase())
		.join('');
const ts = await format(
	`// Generated by scripts/generate-languages.mjs; edit languages.json.
export const TARGET_LANGUAGES = ${JSON.stringify(codes)} as const;
export type TargetLanguage = (typeof TARGET_LANGUAGES)[number];
`,
	{ parser: 'typescript', useTabs: true, singleQuote: true, trailingComma: 'none', printWidth: 100 }
);
const rust = `// Generated by scripts/generate-languages.mjs; edit src/lib/languages.json.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum TargetLanguage {
${codes.map((c) => `    #[serde(rename = "${c}")]\n    ${variant(c)},`).join('\n')}
}

impl TargetLanguage {
    pub fn bcp47(self) -> &'static str {
        match self {
${codes.map((c) => `            Self::${variant(c)} => "${c}",`).join('\n')}
        }
    }

    pub fn supported_by(self, provider: Provider) -> bool {
        match provider {
${['gemini', 'openai', 'ondevice', 'whisper-translate']
	.map(
		(p) =>
			`            Provider::${{ gemini: 'Gemini', openai: 'OpenAi', ondevice: 'OnDevice', 'whisper-translate': 'WhisperTranslate' }[p]} => matches!(\n                self,\n                ${catalog.languages
				.filter((l) => l.providers.includes(p))
				.map((l) => `Self::${variant(l.code)}`)
				.join('\n                    | ')}\n            ),`
	)
	.join('\n')}
            Provider::Mistral | Provider::GeminiTranscribe | Provider::Whisper => true,
        }
    }
}
`;
for (const [path, content] of [
	['src/lib/languageCodes.ts', ts],
	['src-tauri/src/language_codes.rs', rust]
]) {
	const url = new URL(path, root);
	if (process.argv.includes('--check')) {
		if (readFileSync(url, 'utf8').replaceAll('\r\n', '\n') !== content)
			throw new Error(`Regenerate ${path}`);
	} else writeFileSync(fileURLToPath(url), content);
}
